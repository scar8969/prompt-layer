#: Prefix on every job id this adapter issues, so a poll can recognise its own.
JOB_PREFIX = "mock"

#: Separator used to pack facts into the job id. Chosen because it cannot occur
#: in a model key, a hex digest or a decimal number.
_FIELD_SEPARATOR = "|"

#: How long a submitted job stays in "processing" before poll() completes it.
#: Short enough for a person to watch, long enough that the real asynchronous
#: polling path in the job runner is genuinely exercised rather than bypassed.
DEFAULT_PROCESSING_SECONDS = 1.2

#: The one sentence every mock output carries.
PLACEHOLDER_NOTE = (
    "Development placeholder: rendered locally by this platform's own encoder. "
    "No model service was contacted and nothing was billed."
)

#: Durations the placeholder video encoder can actually produce. Each entry is
#: a real number of real frames at the encoder's fixed frame delay, not a
#: plausible-sounding menu of values a real model might accept.
_VIDEO_DURATIONS = (0.44, 0.88, 1.76)


def placeholder_digest_value(parts: Any) -> str:
    """The encoder's seed digest, as hex.

    Kept as a thin wrapper so callers need not import the encoder module, and
    so the hex encoding lives in exactly one place.
    """
    return seed_digest(parts).hex()


def request_seed(request: GenerationRequest) -> str:
    """A stable digest of everything that should change the output.

    Two requests that differ only in whitespace around the prompt are the same
    request; two requests that differ in a parameter are not.
    """
    from ..util import json_dumps

    material = {
        "model": request.model_key,
        "mode": request.mode,
        "prompt": (request.prompt or "").strip(),
        "negative_prompt": (request.negative_prompt or "").strip(),
        "parameters": request.parameters or {},
        "references": [dict(ref) for ref in request.references or ()],
        "mask": request.mask_url or "",
        "seed": request.seed,
    }
    return placeholder_digest_value(json_dumps(material))


def _frames_for(duration: float) -> int:
    frames = int(round(duration * 1000.0 / DEFAULT_GIF_DELAY_MS))
    return max(2, frames)


