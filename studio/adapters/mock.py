"""The development provider: real files, no model, and no pretending otherwise.

Every other adapter in this package talks to a service somebody else operates.
This one does not. It renders an image or a clip locally, from the seed of the
request, and reports it honestly as a development placeholder.

It exists because a platform that can only be exercised by spending money is a
platform nobody can test. The connection wizard offers it, every model built on
it carries the mock flag, and every surface that can display a result is
required to read that flag and label it. Switch this adapter off and the
platform still has no way to invent a successful generation: the fal, OpenAI and
declarative adapters all refuse rather than guess.

Two design decisions are worth stating plainly.

The generated bytes are a pure function of the request. The same prompt at the
same settings produces the same file, byte for byte, which makes the tests
deterministic and makes a repeat run cost nothing.

The job id carries its own history. It encodes the model, the seed and the
submit time, so poll() can answer after a process restart without any in-memory
bookkeeping, and without a stale dictionary silently disagreeing with the
database about what is still running.
"""

