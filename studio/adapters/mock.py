def mock_model(model_key: str) -> Optional[MockModel]:
    return MOCK_MODELS_BY_KEY.get(model_key)


def output_directory(context: AdapterContext) -> str:
    """Where this adapter is allowed to write.

    Configurable per connection so a deployment can point it at a real volume.
    The fallback lives under the system temporary directory because these files
    are staging, not storage: the job runner imports them into the asset store
    and the placeholder is disposable.
    """
    configured = ""
    if isinstance(context.config, dict):
        configured = str(context.config.get("output_dir") or "").strip()
    directory = configured or os.path.join(tempfile.gettempdir(), "studio-mock-output")
    os.makedirs(directory, exist_ok=True)
    return directory


def processing_seconds(context: AdapterContext) -> float:
    raw = None
    if isinstance(context.config, dict):
        raw = context.config.get("processing_seconds")
    if raw is None:
        return DEFAULT_PROCESSING_SECONDS
    try:
        value = float(raw)
    except (TypeError, ValueError):
        return DEFAULT_PROCESSING_SECONDS
    return max(0.0, min(value, 600.0))


def pack_job_id(model_key: str, seed: str, submitted_ms: int, count: int) -> str:
    return _FIELD_SEPARATOR.join(
        (JOB_PREFIX, model_key, seed, str(int(submitted_ms)), str(int(count)))
    )


def unpack_job_id(job_id: str) -> Tuple[str, str, int, int]:
    """Recover the facts a poll needs, or refuse with a usable explanation."""
    parts = str(job_id or "").split(_FIELD_SEPARATOR)
    if len(parts) != 5 or parts[0] != JOB_PREFIX:
        raise ApiError(
            INVALID_RESPONSE,
            "This job id was not issued by the development provider.",
            details={"provider_job_id": job_id},
            hint="Re-submit the generation, or register the model against a real provider.",
        )
    try:
        return parts[1], parts[2], int(parts[3]), int(parts[4])
    except ValueError:
        raise ApiError(
            INVALID_RESPONSE,
            "This job id is missing the time the job was submitted.",
            details={"provider_job_id": job_id},
        ) from None


def render_outputs(
    directory: str, seed: str, modality: str, count: int
) -> Tuple[ProviderOutput, ...]:
    """Write every placeholder this job owes, and describe them truthfully."""
    outputs = []
    for index in range(max(1, count)):
        item_seed = "%s:%d" % (seed, index)
        written = write_placeholder(directory, item_seed, modality)
        outputs.append(
            ProviderOutput(
                url="",
                content_type=written.content_type,
                width=written.width,
                height=written.height,
                duration_seconds=(0.0 if not written.is_video else None),
                file_name=os.path.basename(written.path),
                seed=None,
                provider_asset_id=item_seed,
                metadata=dict(written.to_public(), local_path=written.path),
            )
        )
    return tuple(outputs)


@register
class MockAdapter(ModelAdapter):
    """Renders placeholders locally and says so on every surface."""

    slug = "mock"
    label = "Development placeholder provider"
    summary = (
        "Renders placeholder images and clips on this machine, with no external service "
        "and no cost. Use it to exercise the studios and the job pipeline before you "
        "connect a real provider."
    )
    is_mock = True
    auth_schemes = ("none",)
    discovers_models = True
    supports_cancel = True

    #: Shown by the wizard above the credential fields.
    credential_label = "No credential"
    credential_hint = (
        "This provider runs locally. There is no key to enter, and no request leaves "
        "this machine."
    )
    base_url_hint = "Optional. Leave blank unless you are describing a custom placeholder host."
    default_base_url = ""
    docs_url = ""

    # -- declaration --------------------------------------------------------

    def default_modes(self) -> Tuple[str, ...]:
        return ("text_to_image",)

    def default_capabilities(self, modality: str, modes) -> CapabilityProfile:
        return CapabilityProfile(
            modality=modality,
            modes=tuple(modes),
            notes=(PLACEHOLDER_NOTE,),
        )

    def list_models(self, context: AdapterContext) -> Tuple[DiscoveredModel, ...]:
        return tuple(
            DiscoveredModel(
                model_key=model.key,
                display_name=model.display_name,
                modality=model.modality,
                raw={"summary": model.summary, "mock": True},
            )
            for model in MOCK_MODELS
        )

    def capabilities_for(
        self, context: AdapterContext, model_key: str
    ) -> Optional[CapabilityProfile]:
        model = mock_model(model_key)
        return model.capabilities if model is not None else None

    def accepts_model_key(self, model_key: str) -> bool:
        """Only the three documented placeholder keys can render.

        Without this the studio would let a user register a model with any key
        at all, the job would queue, and the failure would arrive minutes later
        as "the provider does not have a model called that" -- after the user
        had written a prompt and pressed generate. A key this adapter cannot
        render is refused where the user typed it.
        """
        return mock_model(model_key) is not None

    def model_key_hint(self) -> str:
        """The keys that work, for the error message and the wizard."""
        return ", ".join(model.key for model in MOCK_MODELS)

    def parameter_schema_for(self, context: AdapterContext, model_key: str) -> ParameterSchema:
        model = mock_model(model_key)
        return model.schema if model is not None else ParameterSchema()

    # -- operations ---------------------------------------------------------

    def test_connection(self, context: AdapterContext) -> ConnectionTestResult:
        """Prove the local encoder works, and say exactly that and nothing more.

        There is no credential to validate here, so reporting a generic success
        would be meaningless. Instead this performs the one operation the
        provider really has: render a placeholder twice and confirm the result
        is well formed and reproducible.
        """
        started = time.monotonic()
        try:
            first, content_type, width, height, frames = for_modality("connection-test", "image")
            second, _ct, _w, _h, _f = for_modality("connection-test", "image")
        except Exception as exc:  # pragma: no cover - a broken encoder is a broken deployment
            return ConnectionTestResult(
                outcome="provider_error",
                ok=False,
                latency_ms=int((time.monotonic() - started) * 1000),
                message="The local placeholder encoder failed: %s" % exc,
                detail={"verified": "local encoder", "external_call": False},
            )

        reproducible = first == second
        well_formed = first[:8] == b"\x89PNG\r\n\x1a\n" and len(first) > 100
        ok = bool(reproducible and well_formed)
        # "ok" is the one outcome word every surface downstream branches on. An
        # empty string here would read as a success in this module and as an
        # unknown outcome in the client, which shows nothing at all.
        return ConnectionTestResult(
            outcome="ok" if ok else "invalid_response",
            ok=ok,
            latency_ms=int((time.monotonic() - started) * 1000),
            message=(
                "The local placeholder encoder produced a reproducible %s file. "
                "No external service was contacted, so this does not verify any provider "
                "credential." % content_type
            )
            if ok
            else "The local placeholder encoder did not produce a usable file.",
            detail={
                "verified": "local encoder only",
                "external_call": False,
                "billable": False,
                "content_type": content_type,
                "width": width,
                "height": height,
                "frames": frames,
                "bytes": len(first),
                "reproducible": reproducible,
                "mock": True,
            },
        )

    def submit(self, context: AdapterContext, request: GenerationRequest) -> SubmittedJob:
        profile = self.capabilities_for(context, request.model_key)
        if profile is None:
            raise ApiError(
                VALIDATION_FAILED,
                "The development provider does not have a model called that.",
                details={"model_key": request.model_key, "known": sorted(MOCK_MODELS_BY_KEY)},
                hint="Pick one of the placeholder models, or register your own provider.",
            )
        self.validate_input(request, profile)
        seed = request_seed(request)
        # A real submission is what starts the clock. Encoding the moment in the
        # id is what lets a restarted worker finish the job honestly.
        submitted_ms = int(time.time() * 1000)
        count = 1 if profile.modality == "video" else max(1, min(request.count, profile.max_outputs))
        job_id = pack_job_id(request.model_key, seed, submitted_ms, count)
        return SubmittedJob(
            provider_job_id=job_id,
            status_url="",
            result_url="",
            outputs=(),
            raw_status=STATE_QUEUED,
            poll_after_seconds=0.4,
        )

    def poll(self, context: AdapterContext, job: SubmittedJob) -> JobStatus:
        model_key, seed, submitted_ms, count = unpack_job_id(job.provider_job_id)
        model = mock_model(model_key)
        if model is None:
            raise ApiError(
                INVALID_RESPONSE,
                "The development provider no longer knows this model.",
                details={"model_key": model_key, "provider_job_id": job.provider_job_id},
                hint="Re-register the model and submit again.",
            )

        elapsed = time.time() - (submitted_ms / 1000.0)
        delay = processing_seconds(context)

        # A deployment or a test can ask the provider to fail, so the failure
        # path in the runner is reachable without editing this file.
        fail_marker = ""
        if isinstance(context.config, dict):
            fail_marker = str(context.config.get("fail_when_prompt_contains") or "")
        if fail_marker and fail_marker in str(job.raw_status or ""):
            return JobStatus(
                state=STATE_FAILED,
                provider_status="failed",
                message="The development provider was configured to fail this job.",
                error_code="provider_error",
            )

        if elapsed < delay:
            return JobStatus(
                state=STATE_PROCESSING,
                provider_status="processing",
                message="Rendering the placeholder locally.",
                retry_after_seconds=max(0.2, min(1.0, delay - elapsed)),
            )

        outputs = render_outputs(output_directory(context), seed, model.modality, count)
        if not outputs:
            raise ApiError(
                INVALID_RESPONSE,
                "The development provider finished without producing a file.",
                details={"provider_job_id": job.provider_job_id},
            )
        return JobStatus(
            state=STATE_COMPLETED,
            provider_status="completed",
            message="Placeholder rendered locally.",
            outputs=outputs,
        )

    def cancel(self, context: AdapterContext, job: SubmittedJob) -> JobStatus:
        # Nothing is running in the background here, so a cancellation is real.
        return JobStatus(
            state=STATE_CANCELLED,
            provider_status="cancelled",
            message="The development provider stopped before rendering.",
        )

    def estimate_cost(
        self, context: AdapterContext, request: GenerationRequest, profile: CapabilityProfile
    ) -> CostEstimate:
        return CostEstimate(
            currency="",
            amount=0.0,
            is_estimate=False,
            is_billable=False,
            unit="request",
            quantity=1,
            note="The development provider runs on this machine and bills nothing.",
        )

    def parse_error(self, error: ApiError) -> ApiError:
        return error
